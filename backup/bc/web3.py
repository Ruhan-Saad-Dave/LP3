import os
import sys
import warnings

# Suppress minor eth-tester backend notices
warnings.filterwarnings('ignore')

# Prevent self-import collision since this file is named web3.py
_current_dir = os.path.dirname(os.path.abspath(__file__))
_saved_sys_path = list(sys.path)
sys.path = [p for p in sys.path if os.path.abspath(p) != _current_dir]

try:
    import web3
    from web3 import Web3
    try:
        from web3 import EthereumTesterProvider
    except ImportError:
        from web3.providers.eth_tester import EthereumTesterProvider
    _web3_available = True
except ImportError as e:
    _web3_available = False
    _import_err = e
finally:
    sys.path = _saved_sys_path


def simulate_ethereum_transaction(transfer_amount_eth=2.5):
    """
    Simulates connecting to an Ethereum node, querying balances, 
    constructing a transaction payload, executing the transfer, and inspecting the receipt.
    """
    if not _web3_available:
        print(f"[!] Error: Could not import 'web3' package ({_import_err}). Please run: pip install web3 eth-tester py-evm")
        return

    print("=" * 75)
    print("   BLOCKCHAIN TECH: ETHEREUM TRANSACTION SIMULATOR (Web3.py)")
    print("=" * 75)

    # 1. Connect to Simulated In-Memory Ethereum Node
    # (In production, replace with: Web3(Web3.HTTPProvider("https://sepolia.infura.io/v3/YOUR_KEY")))
    w3 = Web3(EthereumTesterProvider())

    if not w3.is_connected():
        print("[-] Error: Could not connect to Ethereum network node.")
        return

    print("[+] Connection Status: Connected to Ethereum EVM Node successfully.")
    print(f"    Current Block Number : {w3.eth.block_number}")
    print(f"    Current Gas Price    : {w3.from_wei(w3.eth.gas_price, 'gwei'):.2f} Gwei")

    # 2. Get Test Accounts generated by provider (Simulating MetaMask Accounts)
    accounts = w3.eth.accounts
    sender_address = accounts[0]
    receiver_address = accounts[1]

    # 3. Check Initial Balances in Wei and Ether
    sender_bal_wei = w3.eth.get_balance(sender_address)
    receiver_bal_wei = w3.eth.get_balance(receiver_address)

    print("\n--- 1. INITIAL ACCOUNT BALANCES ---")
    print(f"Sender Address   : {sender_address}")
    print(f"Sender Balance   : {w3.from_wei(sender_bal_wei, 'ether'):,.4f} ETH ({sender_bal_wei:,} Wei)")
    print(f"Receiver Address : {receiver_address}")
    print(f"Receiver Balance : {w3.from_wei(receiver_bal_wei, 'ether'):,.4f} ETH ({receiver_bal_wei:,} Wei)")

    # 4. Construct Transaction Payload (What MetaMask constructs behind the scenes)
    transfer_wei = w3.to_wei(transfer_amount_eth, 'ether')
    nonce = w3.eth.get_transaction_count(sender_address)
    gas_limit = 21000  # Standard fixed gas limit for plain ETH transfer
    gas_price = w3.eth.gas_price

    tx_payload = {
        'from': sender_address,
        'to': receiver_address,
        'value': transfer_wei,
        'gas': gas_limit,
        'gasPrice': gas_price,
        'nonce': nonce
    }

    print("\n--- 2. CONSTRUCTED TRANSACTION PAYLOAD (METAMASK FORMAT) ---")
    print(f"  From            : {tx_payload['from']}")
    print(f"  To              : {tx_payload['to']}")
    print(f"  Value to Send   : {transfer_amount_eth} ETH ({transfer_wei:,} Wei)")
    print(f"  Gas Limit       : {gas_limit} units")
    print(f"  Gas Price       : {w3.from_wei(gas_price, 'gwei'):.2f} Gwei")
    print(f"  Account Nonce   : {nonce} (Transaction sequence number)")

    # 5. Send Transaction & Mine into Block
    print("\n[+] Signing and broadcasting transaction to the network...")
    tx_hash = w3.eth.send_transaction(tx_payload)
    print(f"    Transaction Broadcast! Tx Hash: 0x{tx_hash.hex()}")

    # 6. Wait for Transaction Receipt (Confirmation)
    tx_receipt = w3.eth.wait_for_transaction_receipt(tx_hash)
    gas_used = tx_receipt['gasUsed']
    actual_fee_wei = gas_used * gas_price
    actual_fee_eth = w3.from_wei(actual_fee_wei, 'ether')

    print("\n--- 3. CONFIRMED TRANSACTION RECEIPT (BLOCKCHAIN PROOF) ---")
    print(f"  Transaction Hash : 0x{tx_receipt['transactionHash'].hex()}")
    print(f"  Mined in Block   : #{tx_receipt['blockNumber']}")
    print(f"  Gas Limit        : {gas_limit}")
    print(f"  Gas Used         : {gas_used} units")
    print(f"  Tx Fee Paid      : {actual_fee_eth:.8f} ETH ({actual_fee_wei:,} Wei)")
    status_str = "1 (SUCCESS / CONFIRMED)" if tx_receipt['status'] == 1 else "0 (REVERTED)"
    print(f"  Execution Status : {status_str}")

    # 7. Verify Updated Balances
    updated_sender_bal = w3.eth.get_balance(sender_address)
    updated_receiver_bal = w3.eth.get_balance(receiver_address)

    print("\n--- 4. FINAL ACCOUNT BALANCES ---")
    print(f"Sender Balance   : {w3.from_wei(updated_sender_bal, 'ether'):,.6f} ETH (Deducted {transfer_amount_eth} ETH + Gas Fee)")
    print(f"Receiver Balance : {w3.from_wei(updated_receiver_bal, 'ether'):,.6f} ETH (Credited {transfer_amount_eth} ETH)")
    print("=" * 75)


def safe_input(prompt, default_val):
    try:
        val = input(prompt).strip()
        return val if val else default_val
    except (EOFError, KeyboardInterrupt):
        return default_val


def main():
    print("Choose Mode:")
    print("  1. Run Standard 2.5 ETH Peer-to-Peer Transfer Simulation [Default]")
    print("  2. Specify Custom Transfer Amount")
    choice = safe_input("Enter choice (1/2) [Default: 1]: ", "1")

    if choice == "2":
        amt_str = safe_input("Enter amount of ETH to transfer: ", "5.0")
        try:
            amt = float(amt_str)
        except ValueError:
            amt = 2.5
        simulate_ethereum_transaction(transfer_amount_eth=amt)
    else:
        simulate_ethereum_transaction(transfer_amount_eth=2.5)


if __name__ == "__main__":
    main()
